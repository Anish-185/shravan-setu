"""Write docs/TELUGU_STRINGS.md (every Telugu text the project needs, in one list) and docs/VOICE_SCRIPT.md
(the lines to record). Sources: screener/src/i18n/strings.json (app text + voice lines) and config/screening.json
(triage questions, reminder template). Telugu is written, or reviewed and approved line by line, by a native Telugu
speaker (CLAUDE.md; review record docs/TELUGU_REVIEW.md).

    python scripts/telugu_strings.py           (rewrite both docs)
    python scripts/telugu_strings.py --check   (exit 1 if either doc is out of date; run by pytest)
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
STRINGS = ROOT / "screener" / "src" / "i18n" / "strings.json"
CONFIG = ROOT / "config" / "screening.json"
DOCS = {"strings": ROOT / "docs" / "TELUGU_STRINGS.md", "voice": ROOT / "docs" / "VOICE_SCRIPT.md"}


def cell(text):
    return str(text).replace("|", "\\|").replace("\n", " ")


def rows():
    """(id, English, Telugu or blank, where it appears, file to edit) for everything that needs Telugu."""
    out = []
    for key, v in json.loads(STRINGS.read_text()).items():
        out.append((key, v["en"], "" if v["te"] == "TODO_TE" else v["te"], v["where"],
                    "screener/src/i18n/strings.json"))
    cfg = json.loads(CONFIG.read_text())
    for q in cfg["triage"]["questions"]["value"]:
        out.append((f"triage.{q['id']}", q["en"], "" if q["te"] == "TODO_TE" else q["te"],
                    "Triage checklist question (yes/no)", "config/screening.json triage.questions"))
    rem = cfg["reminders"]["missed_camp"]["value"]
    out.append(("reminders.missed_camp", rem["en"], "" if rem["te"] == "TODO_TE" else rem["te"],
                "Stubbed reminder text when a case is marked missed (logged, never sent)",
                "config/screening.json reminders.missed_camp"))
    out.append(("reminders.missed_camp.date", rem["date"]["en"], "" if rem["date"]["te"] == "TODO_TE" else rem["date"]["te"],
                "Fills {date} in the reminder above when a camp date is known ({date} = 24 Oct 2026 in English, "
                "24-10-2026 in Telugu)", "config/screening.json reminders.missed_camp.date"))
    return out


def strings_doc():
    r = rows()
    todo = sum(1 for x in r if not x[2])
    lines = [
        "# Telugu strings (for [TELUGU_SPEAKER])",
        "",
        "Generated by `python scripts/telugu_strings.py` — edit the sources, not this file.",
        "",
        f"{len(r)} texts, {todo} still need Telugu. Please write the Telugu in the last column (or in a copy of this",
        "list), keeping every `{placeholder}` exactly as it is: the app fills it in (a name, a number, a date).",
        "PASS / RETEST / REFER stay in English. A machine-assisted draft is allowed only if a native speaker reviews",
        "and approves every line (project rule).",
        "",
        "After filling: copy each Telugu text into the `te` field of the file named in the \"Edit in\" column",
        "(replacing `TODO_TE`), then run `python scripts/telugu_strings.py` again. Until then the app shows the English",
        "text with a `[TODO_TE]` marker in Telugu mode.",
        "",
        "| # | ID | English | Where it appears | Edit in | Telugu |",
        "|---|---|---|---|---|---|",
    ]
    for i, (key, en, te, where, src) in enumerate(r, 1):
        lines.append(f"| {i} | `{key}` | {cell(en)} | {cell(where)} | `{src}` | {cell(te)} |")
    return "\n".join(lines) + "\n"


def voice_doc():
    voice = [(k, v) for k, v in json.loads(STRINGS.read_text()).items() if "file" in v]
    lines = [
        "# Voice script (for [TELUGU_SPEAKER])",
        "",
        "Generated by `python scripts/telugu_strings.py` — edit `screener/src/i18n/strings.json`, not this file.",
        "",
        "Lines the child hears through the earphones, in Telugu (text also in `docs/TELUGU_STRINGS.md`). Recorded by a",
        "native speaker; never synthetic voices.",
        "",
        "Recording: a quiet room, phone or laptop mic about 20 cm away, calm and friendly, slow and clear, about",
        "1 second of silence before and after. Save each line as `.mp3` with the exact file name below into",
        "`screener/assets/voice/te/` (the app plays MP3 directly), and set `\"recorded\": true` for that entry in",
        "`strings.json` so the \"voice placeholder\" tag disappears. Before committing, check with ffmpeg that the",
        "peak is below 0 dBFS (no clipping) and that integrated loudness is within about 3 LU of the other lines.",
        "",
        "| File | English meaning | Where it plays | Telugu text | Recorded |",
        "|---|---|---|---|---|",
    ]
    for _, v in voice:
        te = "" if v["te"] == "TODO_TE" else v["te"]
        lines.append(f"| `{v['file']}` | {cell(v['en'])} | {cell(v['where'])} | {cell(te)} | "
                     f"{'yes' if v.get('recorded') else 'no (silent placeholder)'} |")
    return "\n".join(lines) + "\n"


def main(argv):
    docs = {"strings": strings_doc(), "voice": voice_doc()}
    if "--check" in argv:
        stale = [str(DOCS[k].relative_to(ROOT)) for k, text in docs.items()
                 if not DOCS[k].exists() or DOCS[k].read_text() != text]
        if stale:
            print("out of date (run python scripts/telugu_strings.py):", ", ".join(stale))
            return 1
        return 0
    for k, text in docs.items():
        DOCS[k].write_text(text)
        print(f"wrote {DOCS[k].relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
